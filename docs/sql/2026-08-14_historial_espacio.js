/**
 * Auditoría del ESPACIO/FECHAS del flujo de aprobación:
 *  - Tabla nueva EVENTO_ESPACIO_HISTORIAL (propia, permitida): cada fila
 *    registra qué se SOLICITÓ, cuándo se MOVIÓ (y a qué sala/fechas), quién
 *    APROBÓ y quién PUBLICÓ. DETALLE = JSON {de:{...}, a:{...}}.
 *  - Estado nuevo REUBICADO en EVENTOS.ESTADO_APROBACION (gestión operativa
 *    movió el evento; equivale a salón resuelto → sigue publicación).
 */
const oracledb = require('oracledb');

const PASOS = [
  `CREATE TABLE EVENTO_ESPACIO_HISTORIAL (
     ID_HISTORIAL NUMBER GENERATED BY DEFAULT AS IDENTITY,
     ID_EVENTO NUMBER NOT NULL,
     TIPO VARCHAR2(20) NOT NULL,
     USUARIO VARCHAR2(150),
     FECHA DATE DEFAULT SYSDATE NOT NULL,
     DETALLE CLOB,
     CONSTRAINT PK_EVENTO_ESP_HIST PRIMARY KEY (ID_HISTORIAL),
     CONSTRAINT CK_EVENTO_ESP_HIST_TIPO CHECK
       (TIPO IN ('SOLICITADO','MOVIDO','APROBADO','PUBLICADO','RECHAZADO')),
     CONSTRAINT CK_EVENTO_ESP_HIST_JSON CHECK (DETALLE IS JSON)
   )`,
  `CREATE INDEX IX_EVENTO_ESP_HIST_EVENTO ON EVENTO_ESPACIO_HISTORIAL (ID_EVENTO)`,
  // Estado nuevo REUBICADO → recrear NUESTRO check (creado por nosotros el 2026-08-05)
  `ALTER TABLE EVENTOS DROP CONSTRAINT CK_EVENTOS_ESTADO_APROB`,
  `ALTER TABLE EVENTOS ADD CONSTRAINT CK_EVENTOS_ESTADO_APROB
     CHECK (ESTADO_APROBACION IS NULL OR
            ESTADO_APROBACION IN ('BORRADOR','SALON_APROBADO','REUBICADO','PUBLICADO','RECHAZADO'))`,
];

(async () => {
  const c = await oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECT_STRING,
  });
  for (const sql of PASOS) {
    try {
      await c.execute(sql, [], { autoCommit: true });
      console.log('OK  →', sql.replace(/\s+/g, ' ').slice(0, 80));
    } catch (e) {
      const m = String(e.message);
      if (m.includes('ORA-00955') || m.includes('ORA-01430') || m.includes('ORA-02264') || m.includes('ORA-01418')) {
        console.log('YA EXISTÍA/N.A. →', sql.replace(/\s+/g, ' ').slice(0, 60));
      } else if (m.includes('ORA-02443')) {
        console.log('CONSTRAINT NO EXISTÍA (se crea nueva) →', sql.replace(/\s+/g, ' ').slice(0, 60));
      } else throw e;
    }
  }
  const chk = await c.execute(
    `SELECT SEARCH_CONDITION_VC FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'CK_EVENTOS_ESTADO_APROB'`,
    [], { outFormat: oracledb.OUT_FORMAT_OBJECT },
  );
  console.log('CHECK:', chk.rows[0]?.SEARCH_CONDITION_VC?.slice(0, 140));
  const t = await c.execute(
    `SELECT COUNT(*) AS N FROM USER_TABLES WHERE TABLE_NAME = 'EVENTO_ESPACIO_HISTORIAL'`,
    [], { outFormat: oracledb.OUT_FORMAT_OBJECT },
  );
  console.log('TABLA HISTORIAL:', t.rows[0].N === 1 ? 'OK' : 'FALTA');
  await c.close();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
