/**
 * SUSCRIPCIONES Y LICENCIAS — tablas NUEVAS (no se toca ninguna compartida).
 *
 * Modelo:
 *   PLANES               catálogo de planes vendibles (días, topes, precio)
 *   SUSCRIPCIONES        una fila POR COMPRA. Nunca se sobrescribe: al renovar
 *                        se inserta otra fila, así queda el historial completo.
 *   LICENCIAS_ONPREMISE  los tokens on-premise (prueba de 5 días + permanente).
 *                        Se guarda el HASH del token, nunca el token en claro.
 *
 * Decisión de diseño importante: NO se añade nada a INSTITUCIONES. El corte por
 * vencimiento reutiliza el mecanismo que YA existe y está probado —poner
 * INSTITUCIONES.ESTADO en 'SUSPENDIDA'—, que a su vez ya bloquea el login del
 * panel y oculta los eventos de las apps. La razón del corte se sabe mirando
 * SUSCRIPCIONES, no duplicando estado en la tabla compartida.
 *
 * Todas las fechas de corte se interpretan en horario de Ecuador
 * (America/Guayaquil, UTC-5 todo el año). Ver suscripciones.service.ts.
 *
 * Ejecutar:  node docs/sql/2026-08-15_suscripciones.js
 */
const oracledb = require('oracledb');

const SENTENCIAS = [
  // ---------------------------------------------------------------- PLANES
  `CREATE TABLE PLANES (
     ID_PLAN            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     CODIGO             VARCHAR2(30)  NOT NULL,
     NOMBRE             VARCHAR2(120) NOT NULL,
     DIAS               NUMBER(5)     NOT NULL,
     MAX_EVENTOS        NUMBER(6),
     MAX_USUARIOS       NUMBER(6),
     MAX_PARTICIPANTES  NUMBER(8),
     PRECIO             NUMBER(12,2),
     MONEDA             VARCHAR2(3)   DEFAULT 'USD',
     ES_ONPREMISE       CHAR(1)       DEFAULT 'N',
     ACTIVO             CHAR(1)       DEFAULT 'S',
     FECHA_REGISTRO     DATE          DEFAULT SYSDATE
   )`,
  `ALTER TABLE PLANES ADD CONSTRAINT UX_PLANES_CODIGO UNIQUE (CODIGO)`,

  // --------------------------------------------------------- SUSCRIPCIONES
  `CREATE TABLE SUSCRIPCIONES (
     ID_SUSCRIPCION     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     ID_INSTITUCION     NUMBER        NOT NULL,
     ID_PLAN            NUMBER,
     COMPRADOR_EMAIL    VARCHAR2(160) NOT NULL,
     COMPRADOR_NOMBRE   VARCHAR2(160),
     FECHA_COMPRA       DATE          NOT NULL,
     FECHA_INICIO       DATE          NOT NULL,
     FECHA_FIN          DATE          NOT NULL,
     DIAS               NUMBER(5)     NOT NULL,
     MONTO              NUMBER(12,2),
     MONEDA             VARCHAR2(3)   DEFAULT 'USD',
     REFERENCIA_PAGO    VARCHAR2(120),
     -- ACTIVA | VENCIDA | CANCELADA | REEMPLAZADA
     ESTADO             VARCHAR2(20)  DEFAULT 'ACTIVA' NOT NULL,
     -- huella de los avisos ya enviados, para no repetirlos cada noche
     AVISO_ENVIADO      NUMBER(3),
     FECHA_CORTE        DATE,
     NOTAS              VARCHAR2(500),
     CREADO_POR         VARCHAR2(60),
     FECHA_REGISTRO     DATE          DEFAULT SYSDATE,
     MODIFICADO_POR     VARCHAR2(60),
     FECHA_MODIFICACION DATE
   )`,
  `ALTER TABLE SUSCRIPCIONES ADD CONSTRAINT FK_SUSC_INSTITUCION
     FOREIGN KEY (ID_INSTITUCION) REFERENCES INSTITUCIONES (ID_INSTITUCION)`,
  `ALTER TABLE SUSCRIPCIONES ADD CONSTRAINT FK_SUSC_PLAN
     FOREIGN KEY (ID_PLAN) REFERENCES PLANES (ID_PLAN)`,
  // el trabajo nocturno busca por estado + fecha de fin: este índice lo cubre
  `CREATE INDEX IX_SUSC_ESTADO_FIN ON SUSCRIPCIONES (ESTADO, FECHA_FIN)`,
  `CREATE INDEX IX_SUSC_INSTITUCION ON SUSCRIPCIONES (ID_INSTITUCION, FECHA_FIN DESC)`,

  // ---------------------------------------------------- LICENCIAS_ONPREMISE
  `CREATE TABLE LICENCIAS_ONPREMISE (
     ID_LICENCIA        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     ID_INSTITUCION     NUMBER        NOT NULL,
     ID_SUSCRIPCION     NUMBER,
     -- PRUEBA (5 días) | PERMANENTE
     TIPO               VARCHAR2(20)  NOT NULL,
     -- solo el hash SHA-256; el token en claro se muestra UNA vez al generarlo
     TOKEN_HASH         VARCHAR2(64)  NOT NULL,
     -- primeros caracteres, para poder identificar la licencia en pantalla
     TOKEN_PREFIJO      VARCHAR2(12)  NOT NULL,
     FECHA_EMISION      DATE          DEFAULT SYSDATE NOT NULL,
     FECHA_EXP          DATE,
     DIAS               NUMBER(5),
     -- ACTIVA | VENCIDA | REVOCADA
     ESTADO             VARCHAR2(20)  DEFAULT 'ACTIVA' NOT NULL,
     EMITIDO_POR        VARCHAR2(60),
     REVOCADO_POR       VARCHAR2(60),
     FECHA_REVOCACION   DATE,
     NOTAS              VARCHAR2(500)
   )`,
  `ALTER TABLE LICENCIAS_ONPREMISE ADD CONSTRAINT FK_LIC_INSTITUCION
     FOREIGN KEY (ID_INSTITUCION) REFERENCES INSTITUCIONES (ID_INSTITUCION)`,
  `ALTER TABLE LICENCIAS_ONPREMISE ADD CONSTRAINT UX_LIC_TOKEN UNIQUE (TOKEN_HASH)`,
  `CREATE INDEX IX_LIC_INSTITUCION ON LICENCIAS_ONPREMISE (ID_INSTITUCION, ESTADO)`,
];

// Planes iniciales. Los topes van en NULL a propósito: hoy solo se registra el
// consumo, no se bloquea. Se calibran cuando haya datos reales de uso.
const PLANES = [
  ['PRUEBA', 'Trial', 15, null, null, null, 0],
  ['MENSUAL', 'Monthly', 30, null, null, null, null],
  ['TRIMESTRAL', 'Quarterly', 90, null, null, null, null],
  ['ANUAL', 'Annual', 365, null, null, null, null],
  ['ONPREMISE_PRUEBA', 'On-premise trial', 5, null, null, null, 0],
  ['ONPREMISE', 'On-premise permanent', 3650, null, null, null, null],
];

(async () => {
  const c = await oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECT_STRING,
  });

  for (const sql of SENTENCIAS) {
    const nombre = sql.slice(0, 60).replace(/\s+/g, ' ');
    try {
      await c.execute(sql);
      console.log('OK   ', nombre);
    } catch (e) {
      // ORA-00955 objeto ya existe · ORA-01430/02275 columna o FK ya existe
      const repetido = /ORA-00955|ORA-01430|ORA-02275|ORA-02261|ORA-00957/.test(e.message);
      console.log(repetido ? 'YA    ' : 'FALLO ', nombre, repetido ? '' : '-> ' + e.message.split('\n')[0]);
      if (!repetido) throw e;
    }
  }

  for (const [codigo, nombre, dias, mx1, mx2, mx3, precio] of PLANES) {
    const r = await c.execute(
      `MERGE INTO PLANES p USING (SELECT :codigo AS CODIGO FROM DUAL) s
         ON (p.CODIGO = s.CODIGO)
       WHEN NOT MATCHED THEN
         INSERT (CODIGO, NOMBRE, DIAS, MAX_EVENTOS, MAX_USUARIOS, MAX_PARTICIPANTES,
                 PRECIO, ES_ONPREMISE)
         VALUES (:codigo, :nombre, :dias, :mx1, :mx2, :mx3, :precio,
                 CASE WHEN :codigo2 LIKE 'ONPREMISE%' THEN 'S' ELSE 'N' END)`,
      { codigo, nombre, dias, mx1, mx2, mx3, precio, codigo2: codigo },
      { autoCommit: true },
    );
    console.log(`plan ${codigo.padEnd(18)} ${r.rowsAffected ? 'creado' : 'ya estaba'}`);
  }

  console.log('\nListo. Tablas de suscripciones y licencias preparadas.');
  await c.close();
})().catch((e) => {
  console.error('ERROR:', e.message);
  process.exit(1);
});
