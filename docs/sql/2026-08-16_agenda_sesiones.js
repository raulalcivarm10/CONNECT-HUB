/**
 * AGENDA DETALLADA POR DÍA — tabla NUEVA (no se toca ninguna compartida).
 *
 * Una fila por línea del Excel del cliente. El AGRUPADO NO se guarda: se calcula
 * al leer. Motivo: en el Excel, cuando HORARIO y SALON vienen vacíos la fila es
 * "otro conferencista del mismo bloque", y ese mismo bloque puede contener:
 *   - varias charlas distintas (10:10 Aula Magna: 3 ponentes, 3 temas distintos)
 *   - una sola charla con varios panelistas (17:15 roundtable: 4 ponentes, 1 tema)
 * Guardando plano y agrupando por (HORA_INICIO, HORA_FIN, SALON) y luego por TEMA
 * se cubren los dos casos sin obligar al cliente a cambiar cómo arma su Excel.
 *
 * DIA_ORDEN (1, 2, 3…) es lo que manda, NO la fecha escrita en el Excel: el
 * cliente confirmó que las fechas de su archivo estaban corridas y que la primera
 * hoja de días corresponde al primer día del evento. Mapear por orden también
 * evita tener que corregir el archivo cada edición.
 *
 * Ejecutar:
 *   docker compose run --rm -v /root/app/docs/sql:/app/migraciones \
 *     --entrypoint node api /app/migraciones/2026-08-16_agenda_sesiones.js
 */
const oracledb = require('oracledb');

const SENTENCIAS = [
  `CREATE TABLE EVENTO_AGENDA (
     ID_AGENDA       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     ID_EVENTO       NUMBER        NOT NULL,
     -- día del evento (1 = primer día). Manda sobre cualquier fecha del Excel.
     DIA_ORDEN       NUMBER(3)     NOT NULL,
     HORA_INICIO     VARCHAR2(5),
     HORA_FIN        VARCHAR2(5),
     -- texto libre: son salas del centro de convenciones, no de nuestra tabla
     -- SALONES (Aula Magna, Fundacional, Regente 1, Regentes 2-3, Restaurante…)
     SALON           VARCHAR2(120),
     AREA            VARCHAR2(80),
     TEMA            VARCHAR2(600),
     CONFERENCISTA   VARCHAR2(200),
     NACIONALIDAD    VARCHAR2(80),
     -- PONENCIA | DESCANSO | PROTOCOLO (coffee break, almuerzo, inauguración…)
     TIPO            VARCHAR2(20)  DEFAULT 'PONENCIA' NOT NULL,
     PATROCINADOR    VARCHAR2(160),
     -- conserva el orden original del Excel dentro del día
     ORDEN           NUMBER(5),
     FECHA_REGISTRO  DATE          DEFAULT SYSDATE,
     CREADO_POR      VARCHAR2(60)
   )`,
  `ALTER TABLE EVENTO_AGENDA ADD CONSTRAINT FK_AGENDA_EVENTO
     FOREIGN KEY (ID_EVENTO) REFERENCES EVENTOS (ID_EVENTO)`,
  // la lectura siempre es "toda la agenda de un evento, por día y en orden"
  `CREATE INDEX IX_AGENDA_EVENTO_DIA ON EVENTO_AGENDA (ID_EVENTO, DIA_ORDEN, ORDEN)`,
];

(async () => {
  const c = await oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECT_STRING,
  });

  for (const sql of SENTENCIAS) {
    const nombre = sql.slice(0, 58).replace(/\s+/g, ' ');
    try {
      await c.execute(sql);
      console.log('OK   ', nombre);
    } catch (e) {
      const repetido = /ORA-00955|ORA-01430|ORA-02275|ORA-02261|ORA-00957/.test(e.message);
      console.log(repetido ? 'YA    ' : 'FALLO ', nombre,
        repetido ? '' : '-> ' + e.message.split('\n')[0]);
      if (!repetido) throw e;
    }
  }

  console.log('\nListo. Tabla de agenda detallada preparada.');
  await c.close();
})().catch((e) => {
  console.error('ERROR:', e.message);
  process.exit(1);
});
