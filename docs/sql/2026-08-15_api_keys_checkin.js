/**
 * API keys por institución para integraciones externas (lector de QR de la
 * universidad). La clave NUNCA se guarda en claro: solo su SHA-256 y un
 * prefijo visible para identificarla en el panel.
 */
const oracledb = require('oracledb');

const PASOS = [
  `CREATE TABLE INSTITUCION_API_KEYS (
     ID_API_KEY NUMBER GENERATED BY DEFAULT AS IDENTITY,
     ID_INSTITUCION NUMBER NOT NULL,
     NOMBRE VARCHAR2(150) NOT NULL,
     PREFIJO VARCHAR2(20) NOT NULL,
     CLAVE_HASH VARCHAR2(64) NOT NULL,
     ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
     CREADO_POR VARCHAR2(150),
     FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
     ULTIMO_USO DATE,
     USOS NUMBER DEFAULT 0 NOT NULL,
     CONSTRAINT PK_INST_API_KEYS PRIMARY KEY (ID_API_KEY),
     CONSTRAINT UK_INST_API_KEYS_HASH UNIQUE (CLAVE_HASH),
     CONSTRAINT CK_INST_API_KEYS_ACTIVO CHECK (ACTIVO IN ('S','N'))
   )`,
  `CREATE INDEX IX_INST_API_KEYS_INST ON INSTITUCION_API_KEYS (ID_INSTITUCION)`,
];

(async () => {
  const c = await oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECT_STRING,
  });
  for (const sql of PASOS) {
    try {
      await c.execute(sql, [], { autoCommit: true });
      console.log('OK  →', sql.replace(/\s+/g, ' ').slice(0, 70));
    } catch (e) {
      if (String(e.message).includes('ORA-00955')) {
        console.log('YA EXISTÍA →', sql.replace(/\s+/g, ' ').slice(0, 60));
      } else throw e;
    }
  }
  const cols = await c.execute(
    `SELECT COLUMN_NAME, DATA_TYPE FROM USER_TAB_COLUMNS
      WHERE TABLE_NAME = 'INSTITUCION_API_KEYS' ORDER BY COLUMN_ID`,
    [], { outFormat: oracledb.OUT_FORMAT_OBJECT },
  );
  console.log('TABLA:', cols.rows.map((r) => r.COLUMN_NAME).join(', '));
  await c.close();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
